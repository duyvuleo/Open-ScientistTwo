"""The included pinned engine works without an external checkout or live services."""

import json
import shutil

import pytest
from typer.testing import CliRunner

from scientisttwo.integrations.paperorchestra import cli, runtime
from scientisttwo.research.policy import ResearchPolicy
from test_paperorchestra_runtime import SyntheticPdf, trace


def test_bundled_closure_has_exact_provenance_and_no_git_dependency():
    root = runtime.bundled_upstream_root()
    assert root.is_dir() and not (root / ".git").exists()
    assert runtime.verify_upstream() == runtime.SOURCE_HASHES
    assert runtime.resolve_upstream_root() == root
    provenance = json.loads((root / "PROVENANCE.json").read_text())
    assert provenance["revision"] == runtime.UPSTREAM_REVISION
    assert provenance["source"] == runtime.UPSTREAM_URL
    assert provenance["files"] == runtime.SOURCE_HASHES
    assert provenance["modifications_to_listed_files"] is False


def test_explicit_source_override_is_preserved_and_tampering_is_rejected(tmp_path):
    override = tmp_path / "source"
    shutil.copytree(runtime.bundled_upstream_root(), override)
    assert runtime.resolve_upstream_root(override) == override
    code = override / "methods/agents/outline_agent.py"
    code.write_bytes(code.read_bytes() + b"\n# changed\n")
    with pytest.raises(ValueError, match="source mismatch"):
        runtime.resolve_upstream_root(override)


def test_policy_bundles_only_selected_writer_and_keeps_pdf_and_live_contracts(tmp_path):
    assert ResearchPolicy().writer_backend == "canonical"
    assert ResearchPolicy().paperorchestra_root is None
    with pytest.raises(ValueError, match="pinned PDF image"):
        ResearchPolicy(writer_backend="paperorchestra")
    policy = ResearchPolicy(writer_backend="paperorchestra", compiler_image="sha256:" + "a" * 64)
    assert policy.paperorchestra_root == str(runtime.bundled_upstream_root())
    assert policy.require_pdf and not policy.network_literature
    explicit = ResearchPolicy(writer_backend="paperorchestra", compiler_image="sha256:" + "a" * 64,
                              paperorchestra_root=str(tmp_path / "configured-worker-source"))
    assert explicit.paperorchestra_root == str(tmp_path / "configured-worker-source")
    assert runtime.RuntimeConfig().allow_live is False


def test_bundled_real_agent_code_finishes_with_synthetic_services_only(tmp_path):
    materials = tmp_path / "materials"
    materials.mkdir()
    (materials / "idea_sparse.md").write_text("Synthetic integration demonstration; no novelty claim.")
    (materials / "experimental_log.md").write_text("No experiment results are generated by this unit test.")
    (materials / "citation_map.json").write_text(json.dumps({
        "fixture": {"title": "Explicit fixture", "authors": ["Test author"], "year": 2026}}))
    (materials / "references.bib").write_text("@misc{fixture,title={Explicit fixture}}")
    service = runtime.ScriptedTransport(trace())
    result = runtime.run_paperorchestra(None, materials, tmp_path / "output", service,
        SyntheticPdf(), runtime.RuntimeConfig(allow_synthetic_pdf=True))
    report = json.loads(result.report_path.read_text())
    assert result.status == "success", result.error
    assert report["upstream"]["files"] == runtime.SOURCE_HASHES
    assert report["synthetic_agents"] and report["synthetic_pdf"]
    assert report["observed_tokens"] == 0 and report["completed_calls"] == 12


def test_standalone_cli_resolves_bundle_without_upstream_argument(tmp_path, monkeypatch):
    seen = []
    monkeypatch.setattr(cli, "verify_evidence_bundle", lambda *args: None)

    def verify(root):
        seen.append(root)
        raise ValueError("Stop before PDF/model construction")

    monkeypatch.setattr(runtime, "verify_upstream", verify)
    result = CliRunner().invoke(cli.app, ["run", "--materials", str(tmp_path / "materials"),
        "--output", str(tmp_path / "unused"), "--compiler-image", "sha256:" + "a" * 64])
    assert result.exit_code == 2
    assert seen == [runtime.bundled_upstream_root()]
    assert "Stop before PDF/model construction" in result.stdout
    assert not (tmp_path / "unused").exists()
